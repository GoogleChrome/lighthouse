import fs from 'fs';
import path from 'path';

import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import addFormats from 'ajv-formats';

import {LH_ROOT} from '../shared/root.js';

const schemaPath = path.join(LH_ROOT, 'third-party/ard/spec/schemas/ai-catalog.schema.json');
const outputPath = path.join(LH_ROOT, 'third-party/ard/schema-validator.js');

/**
 * Format standalone code with proper 2-space indentation and formatted schema objects.
 * @param {string} src
 * @return {string}
 */
function formatCode(src) {
  // Format embedded JSON schemas into multi-line indented objects
  const code = src.replace(/const schema(\d+) = (\{.+?\});/g, (match, id, jsonStr) => {
    try {
      const obj = JSON.parse(jsonStr);
      return `const schema${id} = ${JSON.stringify(obj, null, 2)};`;
    } catch {
      return match;
    }
  });

  const lines = code.split('\n');
  let indent = 0;
  const out = [];

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line) {
      out.push('');
      continue;
    }

    // Determine leading closing brackets on this line
    let leadingCloses = 0;
    for (const char of line) {
      if (char === '}' || char === ']' || char === ')') {
        leadingCloses++;
      } else if (char === ' ' || char === ';') {
        continue;
      } else {
        break;
      }
    }

    const lineIndent = Math.max(0, indent - leadingCloses);

    // Format keywords and spacing around braces
    const formattedLine = line
      .replace(/^if\(/, 'if (')
      .replace(/^for\(/, 'for (')
      .replace(/^while\(/, 'while (')
      .replace(/\)\{/g, ') {')
      .replace(/^else\{/, 'else {')
      .replace(/^}else/, '} else');

    out.push('  '.repeat(lineIndent) + formattedLine);

    // Calculate indent for subsequent lines
    const openCount = (line.match(/[{[(]/g) || []).length;
    const closeCount = (line.match(/[}\])]/g) || []).length;
    indent = Math.max(0, indent + openCount - closeCount);
  }

  return out.join('\n');
}

function build() {
  const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));

  const ajv = new Ajv2020({
    allErrors: true,
    allowUnionTypes: true,
    code: {
      source: true,
      esm: true,
      lines: true,
    },
  });
  addFormats(ajv, ['uri', 'date-time']);

  const validate = ajv.compile(schema);
  let moduleCode = standaloneCode(ajv, validate);

  // Use ESM import for ajv-formats instead of CommonJS require in standalone code.
  moduleCode = moduleCode.replace(
    /const formats0 = require\("ajv-formats\/dist\/formats"\)\.fullFormats\.uri;/g,
    'const formats0 = fullFormats.uri;'
  );
  moduleCode = moduleCode.replace(
    /const formats10 = require\("ajv-formats\/dist\/formats"\)\.fullFormats\["date-time"\];/g,
    'const formats10 = fullFormats["date-time"];'
  );

  const formattedModuleCode = formatCode(moduleCode);

  const banner = `/**
 * @license
 * Copyright 2026 Google LLC
 * SPDX-License-Identifier: Apache-2.0
 */

// auto-generated by build/build-ard-schema.js
/* eslint-disable */
// @ts-nocheck

import {fullFormats} from 'ajv-formats/dist/formats.js';

`;

  fs.writeFileSync(outputPath, banner + formattedModuleCode);
  console.log(`Generated ${outputPath}`);
}

build();

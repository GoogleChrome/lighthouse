{
  // eslint-disable-next-line max-len
  const inFile = `${LH_ROOT}/node_modules/chrome-devtools-frontend/front_end/panels/application/components/BackForwardCacheStrings.ts`;
  const outFile = `${LH_ROOT}/core/lib/bf-cache-strings.js`;

  const input = fs.readFileSync(inFile, 'utf-8');

  const uiStringsDeclare = extract(input, 'const UIStrings', '} as const;', [
    [' as const', ''],
  ]);
  const notRestoredReasonDescriptionDeclare =
    extract(input, 'const NotRestoredReasonDescription', '} as const;', [
      [/i18nLazyString/g, 'str_'],
      [/i18n\.i18n\.lockedLazyString/g, ''],
      [': NotRestoredReason', ''],
      [' as const', ''],
      ['@ts-expect-error ', ''],
    ]);

  const extraCode = `
/** @type {Record<string, {name: LH.IcuMessage|string} | undefined>} */
${notRestoredReasonDescriptionDeclare}

export {
  NotRestoredReasonDescription,
};`;
  fs.writeFileSync(outFile, createStringsModule(
    '@paulirish/trace_engine/panels/application/components/BackForwardCacheStrings.js',
    uiStringsDeclare, extraCode));
}

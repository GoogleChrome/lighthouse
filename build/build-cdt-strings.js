/**
 * @param {string} text
 * @param {string|RegExp} searchValue
 * @param {string} replaceValue
 */
function doReplacement(text, searchValue, replaceValue) {
  const newValue = text.replace(searchValue, replaceValue);
  if (newValue === text) throw new Error(`could not find: ${searchValue}`);
  return newValue;
}

/**
 * @param {string} text
 * @param {[string|RegExp, string][]} replacements
 */
function doReplacements(text, replacements) {
  for (const replacement of replacements) {
    text = doReplacement(text, replacement[0], replacement[1]);
  }
  return text;
}

/**
 * @param {string} text
 * @param {string} startPattern
 * @param {string} endPattern
 * @param {[string|RegExp, string][]} replacements
 */
function extract(text, startPattern, endPattern, replacements = []) {
  const startIndex = text.indexOf(startPattern);
  if (startIndex === -1) throw new Error(`could not find: ${startPattern}`);
  const endIndex = text.indexOf(endPattern, startIndex);
  if (endIndex === -1) throw new Error(`could not find: ${endPattern}`);

  const subText = text.substring(startIndex, endIndex + endPattern.length);
  return doReplacements(subText, replacements);
}

/**
 * @param {string} module
 * @param {string} uiStringsDeclare
 * @param {string} extraCode
 */
function createStringsModule(module, uiStringsDeclare, extraCode) {
  return `
// auto-generated by build/build-cdt-strings.js
/* eslint-disable */

import * as i18n from '../lib/i18n/i18n.js';

${uiStringsDeclare}

const str_ = i18n.createIcuMessageFn('node_modules/${module}', UIStrings);

${extraCode}`.trimStart();
}

// core/lib/deprecations-strings.js
{
  let chromiumCommit = '26fd5b50588a0c10c6611b21493af9c30646cd93';
  const isRoll = process.argv.includes('--roll');
  if (isRoll) {
    const headRes = await fetch(
      'https://chromium.googlesource.com/chromium/src/+/refs/heads/main?format=JSON'
    );
    if (!headRes.ok) {
      throw new Error(`Failed to fetch Chromium HEAD: ${headRes.status} ${headRes.statusText}`);
    }
    const headText = await headRes.text();
    const headJson = JSON.parse(headText.replace(/^\)\]\}'\n/, ''));
    chromiumCommit = headJson.commit;
  }

  const url = `https://chromium.googlesource.com/chromium/src/+/${chromiumCommit}/third_party/blink/renderer/core/frame/deprecation/deprecation.json5?format=TEXT`;
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`Failed to fetch deprecation.json5: ${res.status} ${res.statusText}`);
  }
  const json5Text = Buffer.from(await res.text(), 'base64').toString('utf-8');
  const {config: doc} = ts.parseConfigFileTextToJson('deprecation.json5', json5Text);
  if (!doc || !Array.isArray(doc.data)) {
    throw new Error('Failed to parse deprecation.json5');
  }

  /** @type {Record<string, {chromeStatusFeature?: number, milestone?: number}>} */
  const meta = {};
  const uiStringsLines = [];
  for (const entry of doc.data) {
    if ('obsolete_to_be_removed_after_milestone' in entry) continue;

    const name = entry.name;
    /** @type {{chromeStatusFeature?: number, milestone?: number}} */
    const metaForEntry = {};
    if ('chrome_status_feature' in entry) {
      metaForEntry.chromeStatusFeature = entry.chrome_status_feature;
    }
    if ('milestone' in entry) {
      metaForEntry.milestone = entry.milestone;
    }
    if (Object.keys(metaForEntry).length) {
      meta[name] = metaForEntry;
    }

    uiStringsLines.push(
      '  /**',
      `   * @description ${entry.translation_note}`,
      '   */',
      `  ${name}: ${JSON.stringify(entry.message)},`
    );
  }

  const sortedMeta = Object.fromEntries(
    Object.entries(meta).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  );

  let generatedDeprecationSourceText = [
    '// auto-generated by build/build-cdt-strings.js',
    '/* eslint-disable */',
    '',
    'export const UIStrings = {',
    ...uiStringsLines,
    '};',
    '',
    `export const DEPRECATIONS_METADATA = ${JSON.stringify(sortedMeta, null, 2)};`,
    '',
  ].join('\n');
  generatedDeprecationSourceText = doReplacements(generatedDeprecationSourceText, [
    // Some patterns are supported in DevTools UIStrings, but not ours.
    [/\\\\/g, ''],
    [`{imageOrientation: 'from-image'}`, `\\\\{imageOrientation: 'from-image'\\\\}`],
  ]);
  generatedDeprecationSourceText = generatedDeprecationSourceText.replaceAll(
    'https://goo.gle/chrome-insecure-origins',
    'https://www.chromium.org/Home/chromium-security/deprecating-powerful-features-on-insecure-origins/'
  );

  const outFile = `${LH_ROOT}/core/lib/deprecations-strings.js`;
  const existingDeprecations = fs.readFileSync(outFile, 'utf-8');
  if (isRoll && generatedDeprecationSourceText !== existingDeprecations) {
    const selfPath = `${LH_ROOT}/build/build-cdt-strings.js`;
    const selfContent = fs.readFileSync(selfPath, 'utf-8');
    fs.writeFileSync(
      selfPath,
      selfContent.replace(
        /let chromiumCommit = '[a-f0-9]{40}';/,
        `let chromiumCommit = '${chromiumCommit}';`
      )
    );
  }
  fs.writeFileSync(outFile, generatedDeprecationSourceText);
}


import assert from 'assert/strict';
import fs from 'fs';

import jsdom from 'jsdom';

import {LH_ROOT} from '../../shared/root.js';
import {locales} from '../../shared/localization/locales.js';
import {UIStrings} from '../app/src/ui-strings.js';
import {
  DEFAULT_LOCALE,
  SUPPORTED_LOCALES,
  getWebsiteLocale,
  getWebsiteString,
  initWebsiteI18n,
  setWebsiteLocale,
} from '../app/src/website-locale.js';
import * as testHelpers from './test-helpers.js';

const VIEWER_INDEX = fs.readFileSync(LH_ROOT + '/viewer/app/index.html', 'utf8');

/**
 * Mimics the `strings` global generated by build/build-locale-strings.js,
 * with translations taken from the real localization files.
 * @param {string[]} keys
 */
function stringsFor(keys) {
  /** @type {Record<string, Record<string, string>>} */
  const strings = {};
  for (const [locale, lhlMessages] of Object.entries(locales)) {
    /** @type {Record<string, string>} */
    const localizedStrings = {};
    for (const key of keys) {
      const message = lhlMessages[`viewer/app/src/ui-strings.js | ${key}`];
      if (message) localizedStrings[key] = message.message;
    }
    strings[locale] = localizedStrings;
  }
  return strings;
}

describe('WebsiteI18n', () => {
  const allStrings = stringsFor(Object.keys(UIStrings));

  beforeEach(function() {
    testHelpers.setupJsDomGlobals();
  });

  afterEach(testHelpers.cleanupJsDomGlobals);

  describe('localization files', () => {
    it('supports English, Traditional Chinese and Japanese', () => {
      assert.deepEqual(Object.keys(SUPPORTED_LOCALES), ['en-US', 'zh-TW', 'ja']);
      for (const locale of Object.keys(SUPPORTED_LOCALES)) {
        const localized = stringsFor(Object.keys(UIStrings))[locale];
        for (const key of Object.keys(UIStrings)) {
          assert.ok(localized[key], `missing translation of "${key}" for ${locale}`);
        }
      }
    });

    it('has only valid data-i18n values in viewer html', () => {
      const dom = new jsdom.JSDOM(VIEWER_INDEX);
      for (const node of dom.window.document.querySelectorAll('[data-i18n]')) {
        const val = node.getAttribute('data-i18n');
        assert.ok(val in UIStrings, `Invalid data-i18n value of: "${val}" not found.`);
      }
      for (const node of dom.window.document.querySelectorAll('[data-i18n-placeholder]')) {
        const val = node.getAttribute('data-i18n-placeholder');
        assert.ok(val in UIStrings, `Invalid data-i18n-placeholder value of: "${val}" not found.`);
      }
    });
  });

  describe('display locale', () => {
    it('defaults to English', () => {
      assert.equal(DEFAULT_LOCALE, 'en-US');
      assert.equal(getWebsiteLocale(), 'en-US');
    });

    it('remembers the visitor\'s choice', () => {
      setWebsiteLocale('ja');
      assert.equal(getWebsiteLocale(), 'ja');
      setWebsiteLocale('zh-TW');
      assert.equal(getWebsiteLocale(), 'zh-TW');
    });

    it('ignores saved values that are not supported', () => {
      window.localStorage.setItem('lighthouse-website-locale', 'de');
      assert.equal(getWebsiteLocale(), 'en-US');
    });
  });

  describe('rendering', () => {
    it('renders the page in English by default', () => {
      initWebsiteI18n(allStrings);
      assert.equal(document.documentElement.lang, 'en-US');
      assert.equal(document.querySelector('h1')?.textContent, UIStrings.viewerTitle);
      assert.equal(
        document.querySelector('.js-gist-url')?.getAttribute('placeholder'),
        UIStrings.gistUrlPlaceholder);
    });

    it('renders the page in the chosen display language', () => {
      setWebsiteLocale('zh-TW');
      initWebsiteI18n(allStrings);
      const messages = locales['zh-TW'];
      assert.equal(document.documentElement.lang, 'zh-TW');
      assert.equal(document.querySelector('h1')?.textContent,
        messages['viewer/app/src/ui-strings.js | viewerTitle'].message);
      assert.equal(
        document.querySelector('.js-gist-url')?.getAttribute('placeholder'),
        messages['viewer/app/src/ui-strings.js | gistUrlPlaceholder'].message);
    });

    it('renders markdown links as links', () => {
      initWebsiteI18n(allStrings);
      const link = document.querySelector('[data-i18n="diffToolHint"] a');
      assert.ok(link);
      assert.equal(link.getAttribute('href'),
        'https://googlechrome.github.io/lighthouse-ci/difftool/');
    });

    it('switches the display language from the language menu', () => {
      initWebsiteI18n(allStrings);
      const select = /** @type {HTMLSelectElement|null} */ (
        document.querySelector('.js-website-locale'));
      assert.ok(select);
      assert.equal(select.value, 'en-US');
      assert.deepEqual([...select.options].map(option => option.textContent),
        Object.values(SUPPORTED_LOCALES));

      select.value = 'ja';
      select.dispatchEvent(new window.Event('change'));

      assert.equal(document.documentElement.lang, 'ja');
      assert.equal(document.querySelector('h1')?.textContent,
        locales['ja']['viewer/app/src/ui-strings.js | viewerTitle'].message);
      assert.equal(getWebsiteLocale(), 'ja');
    });
  });

  describe('getWebsiteString', () => {
    it('substitutes placeholder values', () => {
      initWebsiteI18n(allStrings);
      const message = getWebsiteString('olderReportWarning',
        {reportVersion: '12.6.0', currentVersion: '13.0.0'});
      assert.ok(message.includes('12.6.0'));
      assert.ok(message.includes('13.0.0'));
      assert.ok(!message.includes('{reportVersion}'));
    });

    it('uses the chosen display language', () => {
      setWebsiteLocale('ja');
      initWebsiteI18n(allStrings);
      assert.equal(getWebsiteString('couldNotReadFile'),
        locales['ja']['viewer/app/src/ui-strings.js | couldNotReadFile'].message);
    });
  });
});
